import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

/** @typedef {{major: number, minor: number, patch: number}} Version */
/** @typedef {{kind: "entry", section: string, scope: string|null, text: string, breaking: boolean, note: string|null, sha: string} | {kind: "hidden", type: string, sha: string} | {kind: "nonconforming", subject: string, reason: string, sha: string}} ParsedCommit */
const SECTIONS = [
	{ section: "breaking", heading: "Breaking Changes", types: [] },
	{ section: "added", heading: "Added", types: ["feat"] },
	{ section: "changed", heading: "Changed", types: ["perf", "revert"] },
	{ section: "fixed", heading: "Fixed", types: ["fix"] },
	{ section: "upstream", heading: "Upstream", types: [] },
];
const HIDDEN = new Set(["refactor", "docs", "test", "build", "ci", "chore", "style"]);
const HEADER = /^(?<type>[a-z]+)(?:\((?<scope>[^()\s]+)\))?(?<bang>!)?: (?<text>\S.*)$/;
const RELEASE = /^chore\(release\): raga v(\d+\.\d+\.\d+)$/;
const INTRO =
	"# Changelog\n\nGenerated by scripts/raga-release.mjs from conventional commits. Do not edit by hand.\n\n";
const USAGE =
	"Usage: node scripts/raga-release.mjs init --base <rev> | version | check | release [patch|minor|major|X.Y.Z] [--dry-run] | lint-msg <file>";

export function parseVersion(text) {
	if (!/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(text)) {
		throw new Error(`invalid version: ${text}`);
	}
	const [major, minor, patch] = text.split(".").map(Number);
	if (![major, minor, patch].every(Number.isSafeInteger)) throw new Error(`invalid version: ${text}`);
	return { major, minor, patch };
}

export function formatVersion({ major, minor, patch }) {
	return `${major}.${minor}.${patch}`;
}

function compare(a, b) {
	return a.major - b.major || a.minor - b.minor || a.patch - b.patch;
}

/** @returns {ParsedCommit} */
export function parseCommit({ sha, subject, body = "" }) {
	const footer = /(?:^|\n)BREAKING(?: CHANGE|-CHANGE):[ \t]*([^\n]*(?:\n[ \t]+[^\n]+)*)/.exec(body);
	const note = footer ? footer[1].trim().replace(/\n[ \t]+/g, " ") || null : null;
	const reverted = /^(Revert|Reapply) "(.+)"$/.exec(subject);
	if (reverted) {
		return {
			kind: "entry",
			section: footer ? "breaking" : "changed",
			scope: null,
			text: `${reverted[1] === "Revert" ? "Reverted" : "Reapplied"}: ${reverted[2]}`,
			breaking: Boolean(footer),
			note,
			sha,
		};
	}
	const match = HEADER.exec(subject);
	if (!match) return { kind: "nonconforming", subject, reason: "expected a conventional commit header", sha };
	const { type, scope, bang, text } = match.groups;
	const section = SECTIONS.find((item) => item.types.includes(type))?.section;
	if (!section && !HIDDEN.has(type))
		return { kind: "nonconforming", subject, reason: `unknown commit type ${type}`, sha };
	const breaking = Boolean(bang || footer);
	if (!breaking && HIDDEN.has(type)) return { kind: "hidden", type, sha };
	return {
		kind: "entry",
		section: breaking ? "breaking" : section,
		scope: scope ?? null,
		text,
		breaking,
		note,
		sha,
	};
}

export function nextVersion(current, entries, syncs, target) {
	if (entries.length + syncs.length === 0) throw new Error("nothing to release");
	const breaking = entries.some((entry) => entry.breaking);
	const added = entries.some((entry) => entry.section === "added");
	const bump = target ?? (breaking && current.major > 0 ? "major" : breaking || added ? "minor" : "patch");
	let next;
	if (bump === "major") next = { major: current.major + 1, minor: 0, patch: 0 };
	else if (bump === "minor") next = { major: current.major, minor: current.minor + 1, patch: 0 };
	else if (bump === "patch") next = { ...current, patch: current.patch + 1 };
	else next = parseVersion(bump);
	if (compare(next, current) <= 0) throw new Error("next version must be greater than current version");
	return parseVersion(formatVersion(next));
}

export function renderSection({ next, date, entries, syncs }) {
	const blocks = [`## [${formatVersion(next)}] - ${date}`];
	for (const { section, heading } of SECTIONS) {
		const lines =
			section === "upstream"
				? syncs.map((sync) => `- Merged pi ${sync.describe} (${sync.count} commits)`)
				: entries
						.filter((entry) => entry.section === section)
						.map((entry) => {
							const text = entry.note ? `${entry.text.replace(/\.$/, "")}. ${entry.note}` : entry.text;
							return `- ${entry.scope ? `**${entry.scope}**: ` : ""}${text} (${entry.sha.slice(0, 7)})`;
						});
		if (lines.length) blocks.push(`### ${heading}\n\n${lines.join("\n")}`);
	}
	return `${blocks.join("\n\n")}\n`;
}

function headings(text) {
	return [...(text ?? "").matchAll(/^## \[(\d+\.\d+\.\d+)\](?:[^\n]*)$/gm)].map((match) => match[1]);
}

export function insertSection(fileText, sectionText, version) {
	if (headings(fileText).includes(version)) return { text: fileText, changed: false };
	if (fileText == null) return { text: `${INTRO}${sectionText}`, changed: true };
	const start = fileText.search(/^## \[/m);
	if (start < 0)
		return {
			text: `${fileText}${fileText.endsWith("\n\n") ? "" : fileText.endsWith("\n") ? "\n" : "\n\n"}${sectionText}`,
			changed: true,
		};
	return { text: `${fileText.slice(0, start)}${sectionText}\n${fileText.slice(start)}`, changed: true };
}

export function lintMessage(text, { merging = false } = {}) {
	const subject = text
		.split(/\r?\n/)
		.filter((line) => !line.startsWith("#"))
		.join("\n")
		.trim()
		.split("\n")[0];
	if ((merging && /^Merge .+/.test(subject)) || /^(fixup!|squash!|amend!) .+/.test(subject)) return [];
	const commit = parseCommit({ sha: "", subject, body: text });
	return commit.kind === "nonconforming" ? [`${commit.reason}: ${subject || "(empty message)"}`] : [];
}

export function lintStagedPaths(paths) {
	return paths
		.filter((path) => /^packages\/[^/]+\/CHANGELOG\.md$/.test(path))
		.map((path) => `upstream-owned changelog must not be staged: ${path}`);
}

function git(cwd, args, { input, allowFailure = false } = {}) {
	const result = spawnSync("git", args, { cwd, input, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
	if (result.error) throw result.error;
	if (result.status !== 0 && !allowFailure)
		throw new Error(result.stderr.trim() || result.stdout.trim() || `git ${args.join(" ")} failed`);
	return result;
}

function output(cwd, args) {
	return git(cwd, args).stdout.trim();
}

function ancestor(cwd, sha, ref) {
	const result = git(cwd, ["merge-base", "--is-ancestor", sha, ref], { allowFailure: true });
	if (result.status > 1) throw new Error(result.stderr.trim());
	return result.status === 0;
}

function readTags(cwd) {
	const names = output(cwd, ["tag", "--merged", "HEAD", "--list", "raga-v*"]).split("\n").filter(Boolean);
	return names
		.map((tag) => {
			const version = parseVersion(tag.slice(6));
			if (output(cwd, ["cat-file", "-t", `refs/tags/${tag}`]) !== "tag")
				throw new Error(`raga tag must be annotated: ${tag}`);
			return { tag, version, sha: output(cwd, ["rev-parse", `${tag}^{commit}`]) };
		})
		.sort((a, b) => compare(b.version, a.version));
}

function boundary(cwd, remote) {
	const refs = output(cwd, ["for-each-ref", "--format=%(refname)", "refs/tags", `refs/remotes/${remote}/`])
		.split("\n")
		.filter(Boolean);
	const tags = refs.filter((ref) => /^refs\/tags\/v[0-9]/.test(ref));
	const remotes = refs.filter((ref) => ref.startsWith(`refs/remotes/${remote}/`));
	return [...(tags.length ? ["--tags=v[0-9]*"] : []), ...(remotes.length ? [`--remotes=${remote}`] : [])];
}

function inBoundary(cwd, sha, bounds) {
	return bounds.length > 0 && output(cwd, ["rev-list", "-1", sha, "--not", ...bounds]) === "";
}

function boundaryProblems(cwd, bounds, remote, current, head) {
	const tags = output(cwd, ["tag", "--list", "raga-v*"])
		.split("\n")
		.filter((tag) => tag && tag !== "raga-v0.0.0");
	const problems = tags
		.filter((tag) => inBoundary(cwd, tag, bounds))
		.map(
			(tag) =>
				`upstream boundary for remote ${remote} contains ${tag}; ${remote} points at raga itself; point ${remote} at pi`,
		);
	if (
		current &&
		output(cwd, ["rev-list", "--first-parent", "--count", `${current.tag}..${head}`]) !== "0" &&
		inBoundary(cwd, head, bounds)
	)
		problems.push(
			`upstream boundary for remote ${remote} contains HEAD with unreleased first-parent commits; point ${remote} at pi`,
		);
	return problems;
}

function readRange(cwd, tag, bounds, head) {
	const args = ["log", "--first-parent", "--reverse", "-z", "--format=%H%x00%P%x00%s%x00%b", `${tag}..${head}`];
	if (bounds.length) args.push("--not", ...bounds);
	const fields = git(cwd, args).stdout.split("\0");
	const entries = [],
		syncs = [],
		problems = [];
	for (let i = 0; i + 3 < fields.length; i += 4) {
		const [sha, parentsText, subject, body] = fields.slice(i, i + 4);
		const parents = parentsText.split(" ").filter(Boolean);
		if (parents.length > 1) {
			if (parents.length !== 2 || !inBoundary(cwd, parents[1], bounds)) {
				problems.push(
					`stray merge ${sha.slice(0, 7)}: ${subject}; raga work must land by rebase or squash; for an upstream sync, restore the upstream remote or fetch pi's v* tags`,
				);
				continue;
			}
			const described = git(cwd, ["describe", "--tags", "--match", "v[0-9]*", parents[1]], { allowFailure: true });
			syncs.push({
				sha,
				describe: described.status === 0 ? described.stdout.trim() : parents[1].slice(0, 7),
				count: Number(output(cwd, ["rev-list", "--count", `${parents[0]}..${parents[1]}`])),
			});
			continue;
		}
		const parsed = parseCommit({ sha, subject, body });
		if (parsed.kind === "entry") entries.push(parsed);
		else if (parsed.kind === "nonconforming")
			problems.push(`nonconforming commit ${sha.slice(0, 7)}: ${subject} (${parsed.reason})`);
	}
	return { entries, syncs, problems, count: Math.floor(fields.length / 4) };
}

function committedChangelog(cwd, rev = "HEAD") {
	if (git(cwd, ["cat-file", "-e", `${rev}:CHANGELOG.md`], { allowFailure: true }).status !== 0) return null;
	return git(cwd, ["show", `${rev}:CHANGELOG.md`]).stdout;
}

function extractSection(text, version) {
	const lines = text.split("\n");
	const start = lines.findIndex((line) => line === `## [${version}]` || line.startsWith(`## [${version}] - `));
	if (start < 0) return null;
	let end = start + 1;
	while (end < lines.length && !lines[end].startsWith("## [")) end++;
	return `${lines.slice(start, end).join("\n").trimEnd()}\n`;
}

function parityProblems(tags, text) {
	const versions = new Set(tags.filter((tag) => tag.tag !== "raga-v0.0.0").map((tag) => formatVersion(tag.version)));
	const released = headings(text);
	return [
		...[...versions]
			.filter((version) => !released.includes(version))
			.map((version) => `missing CHANGELOG.md heading for raga-v${version}`),
		...released
			.filter((version) => !versions.has(version))
			.map((version) => `missing tag raga-v${version} for CHANGELOG.md heading`),
	];
}

function assertClean(cwd, planned) {
	const records = git(cwd, ["status", "--porcelain=v1", "-z", "--untracked-files=all"])
		.stdout.split("\0")
		.filter(Boolean);
	for (let i = 0; i < records.length; i++) {
		const record = records[i];
		if (record.slice(3) !== "CHANGELOG.md" || /[RC]/.test(record.slice(0, 2)))
			throw new Error(`worktree must be clean: ${record.slice(3)}`);
		if (!existsSync(resolve(cwd, "CHANGELOG.md")) || readFileSync(resolve(cwd, "CHANGELOG.md"), "utf8") !== planned)
			throw new Error("dirty CHANGELOG.md does not equal the planned output");
	}
}

function emit(stream, text) {
	stream.write(`${text}\n`);
}

function pushHint(cwd, upstream, version) {
	const remotes = output(cwd, ["remote"]).split("\n");
	const remote = upstream !== "origin" && remotes.includes("origin") ? "origin" : "<raga-remote>";
	return `git push ${remote} HEAD raga-v${version}`;
}

export function main(
	argv,
	{
		cwd = process.cwd(),
		today = new Date().toISOString().slice(0, 10),
		stdout = process.stdout,
		stderr = process.stderr,
	} = {},
) {
	const [command, ...args] = argv;
	const dryRun = args.includes("--dry-run");
	const targets = args.filter((arg) => arg !== "--dry-run");
	const valid =
		(command === "init" && args.length === 2 && args[0] === "--base" && !args[1].startsWith("-")) ||
		(["version", "check"].includes(command) && args.length === 0) ||
		(command === "lint-msg" && args.length === 1 && !args[0].startsWith("-")) ||
		(command === "release" &&
			targets.length <= 1 &&
			args.filter((arg) => arg === "--dry-run").length <= 1 &&
			(!targets.length || /^(patch|minor|major|(?:0|[1-9]\d*)\.(?:0|[1-9]\d*)\.(?:0|[1-9]\d*))$/.test(targets[0])));
	if (!valid) {
		emit(stderr, USAGE);
		return 2;
	}
	try {
		const messagePath = command === "lint-msg" ? resolve(cwd, args[0]) : null;
		cwd = output(cwd, ["rev-parse", "--show-toplevel"]);
		if (command === "lint-msg") {
			const mergeHead = resolve(cwd, output(cwd, ["rev-parse", "--git-path", "MERGE_HEAD"]));
			const merging = existsSync(mergeHead);
			const errors = lintMessage(readFileSync(messagePath, "utf8"), { merging });
			if (!merging)
				errors.push(
					...lintStagedPaths(
						git(cwd, ["diff", "--cached", "--name-only", "--no-renames", "-z"])
							.stdout.split("\0")
							.filter(Boolean),
					),
				);
			for (const error of errors) emit(stderr, error);
			return errors.length ? 1 : 0;
		}
		if (command === "init") {
			const base = output(cwd, ["rev-parse", "--verify", `${args[1]}^{commit}`]);
			if (!ancestor(cwd, base, "HEAD")) throw new Error("base must be an ancestor of HEAD");
			const existing = git(cwd, ["rev-parse", "--verify", "refs/tags/raga-v0.0.0^{commit}"], { allowFailure: true });
			if (existing.status === 0) {
				if (existing.stdout.trim() !== base) throw new Error("raga-v0.0.0 already exists at a different commit");
			} else git(cwd, ["tag", "-a", "raga-v0.0.0", base, "-m", "raga fork point"]);
			emit(stdout, "initialized raga-v0.0.0");
			return 0;
		}
		const head = output(cwd, ["rev-parse", "HEAD"]);
		const tags = readTags(cwd);
		const current = tags[0];
		const remote = process.env.RAGA_UPSTREAM_REMOTE || "upstream";
		const bounds = boundary(cwd, remote);
		const sanity = boundaryProblems(cwd, bounds, remote, current, head);
		if (command === "version") {
			if (!current) throw new Error("no raga version tag; run init --base <rev>");
			const count = output(cwd, ["rev-list", "--first-parent", "--count", `${current.tag}..HEAD`]);
			emit(stdout, `${formatVersion(current.version)}${count === "0" ? "" : `+${count}.g${head.slice(0, 7)}`}`);
			return 0;
		}
		const fileText = committedChangelog(cwd, head);
		if (command === "check") {
			const problems = [...sanity, ...parityProblems(tags, fileText)];
			if (!current) problems.push("no raga version tag; run init --base <rev>");
			else problems.push(...readRange(cwd, current.tag, bounds, head).problems);
			for (const problem of problems) emit(stderr, problem);
			if (!problems.length) emit(stdout, "ok");
			return problems.length ? 1 : 0;
		}
		if (sanity.length) throw new Error(sanity.join("\n"));
		if (!current) throw new Error("no raga version tag; run init --base <rev>");
		const atHead = tags.find((tag) => tag.sha === head);
		if (atHead) {
			emit(stdout, `already released ${formatVersion(atHead.version)}`);
			return 0;
		}
		const pending = output(cwd, [
			"log",
			"--first-parent",
			"--reverse",
			"-z",
			"--format=%H%x00%s",
			`${current.tag}..${head}`,
		]).split("\0");
		let recovery = null;
		for (let i = 0; i + 1 < pending.length; i += 2) {
			const match = RELEASE.exec(pending[i + 1]);
			if (!match) continue;
			const version = formatVersion(parseVersion(match[1]));
			if (
				git(cwd, ["rev-parse", "--verify", "-q", `refs/tags/raga-v${version}`], { allowFailure: true }).status === 0
			)
				continue;
			const text = committedChangelog(cwd, pending[i]);
			const section = text && extractSection(text, version);
			if (!section)
				throw new Error(`release commit ${pending[i].slice(0, 7)} is missing CHANGELOG.md heading ${version}`);
			recovery = { version, section, sha: pending[i] };
			break;
		}
		let plan = recovery;
		if (!plan) {
			const range = readRange(cwd, current.tag, bounds, head);
			if (range.problems.length) throw new Error(range.problems.join("\n"));
			if (range.entries.length + range.syncs.length === 0) {
				const total = Number(output(cwd, ["rev-list", "--first-parent", "--count", `${current.tag}..${head}`]));
				const excluded = total - range.count;
				throw new Error(
					`nothing to release${excluded ? `; ${excluded} first-parent commits were excluded by the upstream boundary` : ""}`,
				);
			}
			const next = nextVersion(current.version, range.entries, range.syncs, targets[0]);
			const version = formatVersion(next);
			const path = resolve(cwd, "CHANGELOG.md");
			const working = existsSync(path) ? readFileSync(path, "utf8") : null;
			const savedDate =
				working !== fileText &&
				working?.match(
					new RegExp(`^## \\[${version.replace(/\./g, "\\.")}\\] - (\\d{4}-\\d{2}-\\d{2})$`, "m"),
				)?.[1];
			const section = renderSection({ next, date: savedDate || today, ...range });
			const inserted = insertSection(fileText, section, version);
			if (!inserted.changed)
				throw new Error(`CHANGELOG.md heading ${version} already exists; refusing another release commit`);
			assertClean(cwd, inserted.text);
			plan = { version, section, path, text: inserted.text, subject: `chore(release): raga v${version}` };
		}
		const { version, section } = plan;
		if (git(cwd, ["rev-parse", "--verify", "-q", `refs/tags/raga-v${version}`], { allowFailure: true }).status === 0)
			throw new Error(`tag raga-v${version} already exists`);
		const operations = [];
		let releaseCommit = plan.sha;
		if (!recovery) {
			const { path, text, subject } = plan;
			operations.push(
				{ label: "write CHANGELOG.md", run: () => writeFileSync(path, text) },
				{ label: "git add CHANGELOG.md", run: () => git(cwd, ["add", "CHANGELOG.md"]) },
				{
					label: `git commit --no-verify -m "${subject}"`,
					// The release commit only writes CHANGELOG.md; the change it releases already passed checks.
					run: () => git(cwd, ["commit", "--no-verify", "-m", subject]),
				},
				{
					label: `verify release commit parent ${head} and subject "${subject}"`,
					run: () => {
						releaseCommit = output(cwd, ["rev-parse", "HEAD"]);
						const [parent, actualSubject] = output(cwd, ["show", "-s", "--format=%P%n%s", releaseCommit]).split(
							"\n",
						);
						if (parent !== head || actualSubject !== subject)
							throw new Error("HEAD moved while creating the release commit; refusing to tag");
					},
				},
			);
		}
		operations.push({
			label: `git tag -a raga-v${version} ${releaseCommit || "<release-commit>"} -F - --cleanup=verbatim`,
			run: () =>
				git(cwd, ["tag", "-a", `raga-v${version}`, releaseCommit, "-F", "-", "--cleanup=verbatim"], {
					input: section,
				}),
		});
		if (dryRun) {
			emit(stdout, `next version ${version}`);
			emit(stdout, section.trimEnd());
		}
		for (const operation of operations) {
			if (dryRun) emit(stdout, operation.label);
			else operation.run();
		}
		if (!dryRun) emit(stdout, recovery ? `recovered raga-v${version}` : `released ${version}`);
		emit(stdout, pushHint(cwd, remote, version));
		return 0;
	} catch (error) {
		emit(stderr, error.message);
		return 1;
	}
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
	process.exit(main(process.argv.slice(2)));
}
